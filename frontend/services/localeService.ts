export function formatPriceByCurrency(amountUSD: number, amountTWD: number, currency: CurrencyAnchor, targetLocale: SupportedLocale): string {
  if (currency === 'TWD') {
    return `NT$ ${Math.round(amountTWD).toLocaleString()}`;
  }

  // If USD selected, calculate local currency equivalent for clarity
  switch (targetLocale) {
    case 'ja':
      return `¥ ${(amountUSD * EXCHANGE_RATES.JPY).toLocaleString('ja-JP', { maximumFractionDigits: 0 })} ($${amountUSD} USD)`;
    case 'ko':
      return `₩ ${(amountUSD * EXCHANGE_RATES.KRW).toLocaleString('ko-KR', { maximumFractionDigits: 0 })} ($${amountUSD} USD)`;
    case 'vi':
      return `${(amountUSD * EXCHANGE_RATES.VND).toLocaleString('vi-VN')} ₫ ($${amountUSD} USD)`;
    case 'th':
      return `฿ ${(amountUSD * EXCHANGE_RATES.THB).toLocaleString('th-TH', { maximumFractionDigits: 0 })} ($${amountUSD} USD)`;
    case 'zh_TW':
      return `NT$ ${Math.round(amountTWD).toLocaleString()} ($${amountUSD} USD)`;
    case 'zh_CN':
    case 'en':
    default:
      return `$${amountUSD.toFixed(2)} USD (NT$ ${Math.round(amountTWD).toLocaleString()})`;
  }
}
